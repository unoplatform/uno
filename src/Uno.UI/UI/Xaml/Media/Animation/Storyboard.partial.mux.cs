#nullable enable

using System;

namespace Microsoft.UI.Xaml.Media.Animation;

partial class Storyboard
{
	/// <summary>
	/// Causes the specified Timeline to target the specified object.
	/// </summary>
	public static void SetTarget(Timeline timeline, DependencyObject target)
		=> Storyboard_SetTarget(timeline, target);

	/// <summary>
	/// Moves the storyboard to the specified animation position. The storyboard performs the requested seek when the next
	/// clock tick occurs.
	/// </summary>
	public void Seek(TimeSpan offset) => SeekCore(offset.TotalSeconds);

	/// <summary>
	/// Gets the clock state of the Storyboard.
	/// </summary>
	public ClockState GetCurrentState() => Timeline_GetClockState(this);

	/// <summary>
	/// Gets the current animation clock time of the Storyboard.
	/// </summary>
	public TimeSpan GetCurrentTime()
	{
		var currentTime = Timeline_GetCurrentTime(this);
		return TimeSpan.FromTicks((long)(currentTime * TimeSpan.TicksPerSecond));
	}

	/// <summary>
	/// Moves the storyboard to the specified animation position immediately (synchronously).
	/// </summary>
	public void SeekAlignedToLastTick(TimeSpan offset) => SeekAlignedToLastTickPublic(offset.TotalSeconds);

	// The remaining methods are generated by the DXaml code generator to call into the core directly.

	/// <summary>
	/// Initiates the set of animations associated with the storyboard.
	/// </summary>
	public void Begin() => BeginCore();

	/// <summary>
	/// Stops the storyboard.
	/// </summary>
	public void Stop() => StopCore();

	/// <summary>
	/// Pauses the animation clock associated with the storyboard.
	/// </summary>
	public void Pause() => PauseCore();

	/// <summary>
	/// Resumes the animation clock, or run-time state, associated with the storyboard.
	/// </summary>
	public void Resume() => ResumeCore();

	/// <summary>
	/// Advances the current time of the storyboard's clock to the end of its active period.
	/// </summary>
	public void SkipToFill() => SkipToFillPublic();
}
