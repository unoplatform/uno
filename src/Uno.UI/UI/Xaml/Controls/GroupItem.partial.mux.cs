#if !HAS_UNO // TODO Uno: GroupItem is only generated by the legacy ItemContainerGenerator.
	private void PrepareItemContainer(object pGroupItem, ItemsControl pItemsControl)
	{
		IItemContainerGenerator spParentGenerator;
		ICollectionViewGroup spGroup;
		object spGroupData;
		GroupStyle pGroupStyleNoRef = null;
		bool bIsPropertyLocal = false;

		try
		{
			ArgumentNullException.ThrowIfNull(pItemsControl);

			if (m_tpGenerator == null)
			{
				return; // user-declared GroupItem
			}

			spGroup = (ICollectionViewGroup)pGroupItem;
			spGroupData = spGroup.Group;

			m_wrParentListViewBaseWeakRef = null;
			if (pItemsControl is ListViewBase)
			{
				m_wrParentListViewBaseWeakRef = new WeakReference<ListViewBase>((ListViewBase)pItemsControl);
			}

			spParentGenerator = m_tpGenerator.m_wrParent;

			// apply the container style
			pGroupStyleNoRef = spParentGenerator.m_tpGroupStyle;
			if (pGroupStyleNoRef != null)
			{
				Style spStyle = pGroupStyleNoRef.ContainerStyle;

				// no ContainerStyle set, try ContainerStyleSelector
				if (spStyle == null)
				{
					StyleSelector spStyleSelector = pGroupStyleNoRef.ContainerStyleSelector;
					if (spStyleSelector != null)
					{
						spStyle = spStyleSelector.SelectStyle(pGroupItem, this);
					}
				}

				// apply the style, if found
				if (spStyle != null)
				{
					// TODO: Set flag StyleSetFromGenerator
					Style = spStyle;
				}
			}

			// forward the header template information

			bIsPropertyLocal = IsPropertyLocal(ContentProperty);

			if (!bIsPropertyLocal)
			{
				Content = spGroupData;
				SetCollectionViewGroup(spGroup);
			}

			bIsPropertyLocal = IsPropertyLocal(ContentTemplateProperty);

			if (!bIsPropertyLocal && pGroupStyleNoRef != null)
			{
				ContentTemplate = pGroupStyleNoRef.HeaderTemplate;
			}

			bIsPropertyLocal = IsPropertyLocal(ContentTemplateSelectorProperty);

			if (!bIsPropertyLocal && pGroupStyleNoRef != null)
			{
				ContentTemplateSelector = pGroupStyleNoRef.HeaderTemplateSelector;
			}
		}
		catch
		{
			SetCollectionViewGroup(null);
			throw;
		}
	}

	private void ClearContainerForItem(object pGroupItem)
	{
		if (m_tpGenerator == null)
		{
			// user-declared GroupItem
			return;
		}

		var spGroup = (ICollectionViewGroup)pGroupItem;
		var spGroupData = spGroup.Group;

		var spParentGenerator = m_tpGenerator.m_wrParent;

		var spContent = Content;
		bool areEqual = Equals(spGroupData, spContent);
		if (areEqual)
		{
			ClearValue(ContentProperty);
			SetCollectionViewGroup(null);
		}

		var pGroupStyleNoRef = spParentGenerator.m_tpGroupStyle;
		if (pGroupStyleNoRef != null)
		{
			var spContentTemplate = ContentTemplate;
			var spHeaderTemplate = pGroupStyleNoRef.HeaderTemplate;
			if (spContentTemplate == spHeaderTemplate)
			{
				ClearValue(ContentTemplateProperty);
			}

			var spContentTemplateSelector = ContentTemplateSelector;
			var spHeaderTemplateSelector = pGroupStyleNoRef.HeaderTemplateSelector;
			if (spContentTemplateSelector == spHeaderTemplateSelector)
			{
				ClearValue(ContentTemplateSelectorProperty);
			}
		}
		m_tpGenerator.RemoveAll();
	}
