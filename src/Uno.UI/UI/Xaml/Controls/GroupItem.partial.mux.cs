	// Obtains the index of the group this GroupItem is representing.
	internal int GetGroupIndex()
	{
		int pGroupIndex = -1;

		if (m_wrParentListViewBaseWeakRef is not null && m_wrParentListViewBaseWeakRef.TryGetTarget(out var spIParentListViewBase))
		{
			var spCollectionView = ((IGeneratorHost)spIParentListViewBase).CollectionView;
			if (spCollectionView is not null)
			{
				var spCollectionGroups = spCollectionView.CollectionGroups;
				if (spCollectionGroups is not null)
				{
					uint groupCount = (uint)spCollectionGroups.Count;

					for (uint i = 0; i < groupCount; i++)
					{
						var spCurrent = spCollectionGroups[(int)i];
						bool areEqual = ReferenceEquals(m_tpCVG, spCurrent);
						if (areEqual)
						{
							pGroupIndex = (int)i;
							break;
						}
					}
				}
			}
		}

		return pGroupIndex;
	}

