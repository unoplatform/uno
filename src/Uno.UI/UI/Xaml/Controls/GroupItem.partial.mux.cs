	// Handler for KeyDown on our HeaderContent part.
	private void OnHeaderKeyDown(object? pSender, KeyRoutedEventArgs pArgs)
	{
		if (m_tpHeaderControl is null)
		{
			return;
		}

		if (pArgs.Handled)
		{
			return;
		}

		if (!m_tpHeaderControl.IsEnabled)
		{
			return;
		}

		if (m_wrParentListViewBaseWeakRef is not null && m_wrParentListViewBaseWeakRef.TryGetTarget(out var pParentListViewBase))
		{
			var originalKey = pArgs.OriginalKey;
			var key = pArgs.Key;

			bool isHandled = pParentListViewBase.OnGroupHeaderKeyDown(this, originalKey, key);

			if (isHandled)
			{
				pArgs.Handled = true;
			}
		}
	}

	// Helper to get the HeaderContent corresponding to this group.
	internal Control? GetHeaderContent() => m_tpHeaderControl;

	// Helper to update m_tpHeaderControl. Attaches and/or detaches OnHeaderKeyDown.
	private void SetHeaderContentReference(Control? pHeaderContent)
	{
		if (m_tpHeaderControl is not null)
		{
			m_tpHeaderControl.KeyDown -= OnHeaderKeyDown;
		}

		if (pHeaderContent is not null)
		{
			pHeaderContent.KeyDown += OnHeaderKeyDown;
		}

		m_tpHeaderControl = pHeaderContent;
	}

