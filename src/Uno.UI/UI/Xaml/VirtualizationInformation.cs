using System;
using System.Collections.Generic;
using System.Text;
using Windows.Foundation;
using Uno;
using System.Runtime.CompilerServices;
using DirectUI;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Controls.Primitives;

namespace Microsoft.UI.Xaml
{
	/// <summary>
	/// Class that holds virtualization information. We do not create this class indiscriminately,
	/// but only for containers that happen to be virtualizing.
	/// </summary>
	// MUX Reference UIElement_Partial.h (UIElement::VirtualizationInformation), tag winui3/release/2.5.1, commit ba3a8d59e6d
	internal sealed class VirtualizationInformation
	{
		private readonly UIElement _owner;
		private Flags _flags;
		private object _dataItem;
		private ContainerContentChangingEventArgs _buildTreeArgs;

		internal StickyHeaderWrapper m_stickyHeaderWrapper;

		public VirtualizationInformation(UIElement owner) => _owner = owner;

		/// <summary>
		/// Marks this as a container generated by, eg, a <see cref="Controls.Primitives.Selector"/>, rather than an element explicitly
		/// defined in xaml.
		/// </summary>
		public bool IsGeneratedContainer
		{
			get => _flags.HasFlag(Flags.IsGeneratedContainer);
			set => SetFlag(Flags.IsGeneratedContainer, value);
		}

		/// <summary>
		/// Marks this as a container defined in the root of an ItemTemplate, so that it can be handled appropriately when recycled.
		/// </summary>
		public bool IsContainerFromTemplateRoot
		{
			get => _flags.HasFlag(Flags.IsContainerFromTemplateRoot);
			set => SetFlag(Flags.IsContainerFromTemplateRoot, value);
		}

		/// <summary>
		/// Marks this as an item being its own container
		/// </summary>
		public bool IsOwnContainer
		{
			get => _flags.HasFlag(Flags.IsOwnContainer);
			set => SetFlag(Flags.IsOwnContainer, value);
		}

		public Rect Bounds { get; set; }

		public Size MeasureSize { get; set; }

		public object Item
		{
			get => _flags.HasFlag(Flags.IsItemLinkedAsOwnContainer) ? _owner : _dataItem;
			set
			{
				if (ReferenceEquals(_owner, value))
				{
					SetFlag(Flags.IsItemLinkedAsOwnContainer, true);
					_dataItem = null;
				}
				else
				{
					SetFlag(Flags.IsItemLinkedAsOwnContainer, false);
					_dataItem = value;
				}
			}
		}

		public bool IsRealized
		{
			get => _flags.HasFlag(Flags.IsRealized);
			set
			{
				SetFlag(Flags.IsRealized, value);

				if (_owner.FindFirstChild() is ListViewBaseItemPresenter chrome)
				{
					chrome.SetShouldRenderChrome(value);
				}
			}
		}

		public bool IsHeader
		{
			get => _flags.HasFlag(Flags.IsHeader);
			set => SetFlag(Flags.IsHeader, value);
		}

		public bool WasRejectedAsAContainerByApp
		{
			get => _flags.HasFlag(Flags.WasRejectedAsAContainerByApp);
			set => SetFlag(Flags.WasRejectedAsAContainerByApp, value);
		}

		public ContainerContentChangingEventArgs GetBuildTreeArgs()
		{
			if (_buildTreeArgs is null)
			{
				_buildTreeArgs = new ContainerContentChangingEventArgs();
#if !HAS_UNO // TODO Uno: ContainerContentChangingEventArgs has no container backpointer yet.
				_buildTreeArgs.RegisterBackpointerToContainer(_owner);
#endif
			}

			return _buildTreeArgs;
		}

		public DataTemplate SelectedTemplate { get; set; }

		public bool IsSticky => m_stickyHeaderWrapper is not null;

		// Container preparation should only be skippable if we've already prepared the container;
		// otherwise, we'll be using a container that has never been prepared even once, which is bad.
		public bool WantsToSkipContainerPreparation
		{
			get => _flags.HasFlag(Flags.WantsToSkipContainerPreparation);
			set => SetFlag(Flags.WantsToSkipContainerPreparation, value);
		}

		public bool MaySkipPreparation => WantsToSkipContainerPreparation && IsPrepared;

		public bool IsPrepared
		{
			get => _flags.HasFlag(Flags.IsPrepared);
			set => SetFlag(Flags.IsPrepared, value);
		}

		[MethodImpl(MethodImplOptions.AggressiveInlining)]
		private void SetFlag(Flags flag, bool value)
		{
			if (value)
			{
				_flags |= flag;
			}
			else
			{
				_flags &= ~flag;
			}
		}

		[Flags]
		private enum Flags
		{
			None = 0,
			IsGeneratedContainer = 1 << 0,
			IsContainerFromTemplateRoot = 1 << 1,
			IsOwnContainer = 1 << 2,
			IsItemLinkedAsOwnContainer = 1 << 3,
			IsRealized = 1 << 4,
			IsHeader = 1 << 5,
			WasRejectedAsAContainerByApp = 1 << 6,
			WantsToSkipContainerPreparation = 1 << 7,
			IsPrepared = 1 << 8,
		}
	}
}
