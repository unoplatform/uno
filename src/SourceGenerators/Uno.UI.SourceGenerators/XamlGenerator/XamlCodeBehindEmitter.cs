#nullable enable

namespace Uno.UI.SourceGenerators.XamlGenerator;

/// <summary>
/// Emits the code-behind source text for a XAML file that has no developer-authored code-behind.
/// </summary>
internal static class XamlCodeBehindEmitter
{
	/// <summary>
	/// Generates a code-behind partial class source string for the given XAML class info.
	/// </summary>
	public static string Emit(XamlClassInfo classInfo, string? filePath = null)
	{
		var sourceComment = filePath is not null ? $"\n// Source: {filePath}" : "";

		// The template below is a verbatim string literal, so its newlines are those of THIS source
		// file as checked out (`* text=auto` yields LF on Unix and CRLF on Windows). Left as-is, the
		// generated code-behind would differ between a Windows and a Unix build of the very same
		// sources -- and it used to mix the two, since the interpolated sourceComment hardcoded CRLF.
		// Normalize to LF so the output is a function of the inputs only.
		return $@"// <auto-generated>
// This file was auto-generated by Uno.UI.SourceGenerators.
// Do not edit this file manually.{sourceComment}
// </auto-generated>

namespace {classInfo.Namespace}
{{
	public sealed partial class {classInfo.ClassName} : {classInfo.BaseTypeFullName}
	{{
		public {classInfo.ClassName}()
		{{
			this.InitializeComponent();
		}}
	}}
}}
".Replace("\r\n", "\n");
	}

	/// <summary>
	/// Returns the hint name for a generated code-behind source file.
	/// </summary>
	public static string GetHintName(XamlClassInfo classInfo)
		=> $"{classInfo.FullClassName}.codebehind.g.cs";
}
