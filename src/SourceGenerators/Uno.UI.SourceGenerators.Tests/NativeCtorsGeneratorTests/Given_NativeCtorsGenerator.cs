using System.Text;
using Microsoft.CodeAnalysis.Text;
using Uno.UI.SourceGenerators.NativeCtor;
using Uno.UI.SourceGenerators.Tests.Verifiers;

namespace Uno.UI.SourceGenerators.Tests.NativeCtorsGeneratorTests;

using Verify = CSharpSourceGeneratorVerifier<NativeCtorsGenerator>;

[TestClass]
public class Given_NativeCtorsGenerator
{
	// Minimal stand-ins for the .NET for iOS types the generator looks up, so the tests do not need the iOS workload.
	private const string UIKitStubs = """
		namespace ObjCRuntime
		{
			public struct NativeHandle
			{
				public static implicit operator NativeHandle(System.IntPtr value) => default;
			}
		}

		namespace Foundation
		{
			[System.AttributeUsage(System.AttributeTargets.Class)]
			public sealed class RegisterAttribute : System.Attribute
			{
				public RegisterAttribute() { }
				public RegisterAttribute(string name) { }
			}
		}

		namespace UIKit
		{
			public class UIView
			{
				public UIView() { }
				protected UIView(ObjCRuntime.NativeHandle handle) { }
			}
		}
		""";

	private const string GlobalConfig = """
		is_global = true
		build_property.Configuration = Release
		""";

	[TestMethod]
	public async Task When_Partial_UIView_Subclass()
	{
		const string inputSource = """
			namespace TestNs
			{
				public partial class MyView : UIKit.UIView
				{
				}
			}
			""";

		const string expectedCode = """
			// <auto-generated>
			// *************************************************************
			// This file has been generated by Uno.UI (NativeCtorsGenerator)
			// *************************************************************
			// </auto-generated>

			using System;

			namespace TestNs
			{
				#if __IOS__ || __TVOS__
				[global::Foundation.Register()]
				#endif
				partial class MyView
				{
					/// <summary>
					/// Initializes a new instance of the class.
					/// </summary>
					public MyView() { }

			#if __ANDROID__
					/// <summary>
					/// Native constructor, do not use explicitly.
					/// </summary>
					/// <remarks>
					/// Used by the .NET for Android runtime to materialize native
					/// objects that may have been collected in the managed world.
					/// </remarks>
					public MyView(IntPtr javaReference, global::Android.Runtime.JniHandleOwnership transfer) : base (javaReference, transfer) { }
			#endif
			#if __IOS__ || __TVOS__
					/// <summary>
					/// Native constructor, do not use explicitly.
					/// </summary>
					/// <remarks>
					/// Used by the .NET for iOS runtime to materialize native
					/// objects that may have been collected in the managed world.
					/// </remarks>
					public MyView(IntPtr handle) : base (handle) { }
					/// <summary>
					/// Native constructor, do not use explicitly.
					/// </summary>
					/// <remarks>
					/// Used by the .NET for iOS runtime to materialize native
					/// objects that may have been collected in the managed world.
					/// </remarks>
					public MyView(global::ObjCRuntime.NativeHandle handle) : base (handle) { }
			#endif
				}
			}

			""";

		var test = CreateTest(inputSource);
		// AddSource(string, string) hashes with the compilation's algorithm, SHA-256.
		test.TestState.GeneratedSources.Add((typeof(NativeCtorsGenerator), "TestNs.MyView.cs", SourceText.From(expectedCode, Encoding.UTF8, SourceHashAlgorithm.Sha256)));

		await test.RunAsync();
	}

	[TestMethod]
	public async Task When_NonPartial_UIView_Subclass()
	{
		const string inputSource = """
			namespace TestNs
			{
				public class MyView : UIKit.UIView
				{
				}
			}
			""";

		await CreateTest(inputSource).RunAsync();
	}

	[TestMethod]
	public async Task When_Partial_UIView_Subclass_In_NonPartial_Type()
	{
		const string inputSource = """
			namespace TestNs
			{
				public class Outer
				{
					public partial class MyView : UIKit.UIView
					{
					}
				}
			}
			""";

		await CreateTest(inputSource).RunAsync();
	}

	private static Verify.Test CreateTest(string inputSource)
		=> new()
		{
			ReferenceAssemblies = _Dotnet.Current.ReferenceAssemblies,
			TestState =
			{
				Sources = { inputSource, UIKitStubs },
				AnalyzerConfigFiles = { ("/.globalconfig", GlobalConfig) },
			},
		};
}
