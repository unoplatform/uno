/// <summary>
/// Writes the source file for the generated dependency properties of one type.
/// </summary>
internal static class DependencyPropertyEmitter
{
	private const string DependencyPropertyType = "global::Microsoft.UI.Xaml.DependencyProperty";
	private const string DependencyObjectType = "global::Microsoft.UI.Xaml.DependencyObject";
	private const string BoxesNamespace = "global::" + BoxesInfo.Namespace;
	private const string FlagsFieldPrefix = "__generatedDependencyPropertyFlags";

	public static SourceText Emit(DependencyPropertyTypeInfo type, BoxesInfo boxes)
	{
		var builder = new IndentedStringBuilder();
		builder.AppendLineIndented("// <auto-generated/>");
		builder.AppendLineIndented("#nullable disable");

		var cacheBits = AllocateCacheBits(type.Properties, out var flagsFieldCount);
		var backingFieldOwners = new List<(HierarchyInfo Owner, List<string> Fields)>();

		WriteHierarchy(builder, type.ContainingType, () =>
		{
			for (var i = 0; i < flagsFieldCount; i++)
			{
				builder.AppendLineIndented($"private uint {FlagsFieldPrefix}{i};");
				builder.AppendLine();
			}

			for (var i = 0; i < type.Properties.Count; i++)
			{
				if (i > 0)
				{
					builder.AppendLine();
				}

				var property = type.Properties[i];
				WriteIdentifier(builder, property);
				builder.AppendLine();

				if (property.Attached is { } attached)
				{
					WriteAttachedProperty(builder, type.ContainingType, property, attached, boxes, backingFieldOwners);
				}
				else if (property.Instance is { } instance)
				{
					WriteInstanceProperty(builder, type.ContainingType, property, instance, cacheBits[i], boxes);
				}
			}
		});

		foreach (var (owner, fields) in backingFieldOwners)
		{
			WriteHierarchy(builder, owner, () =>
			{
				foreach (var field in fields)
				{
					builder.AppendLineIndented(field);
				}
			});
		}

		// Avoids a large object heap allocation for types with many properties, such as UIElement.
		return new StringBuilderBasedSourceText(builder.Builder);
	}

	private static void WriteIdentifier(IndentedStringBuilder builder, DependencyPropertyInfo property)
	{
		var identifierName = property.Name + "Property";
		if (property.Identifier.IsExplicit)
		{
			// Partial property implementations can't have initializers, so the eager value lives in a field.
			builder.AppendLineIndented($"private static readonly {DependencyPropertyType} __{identifierName} = Create{identifierName}();");
			builder.AppendLine();
			builder.AppendLineIndented($"{property.Identifier.Modifiers} {DependencyPropertyType} {identifierName} {{ get => __{identifierName}; }}");
		}
		else
		{
			builder.AppendLineIndented($"{property.Identifier.Modifiers} {DependencyPropertyType} {identifierName} {{ get; }} = Create{identifierName}();");
		}
	}

	private static void WriteInstanceProperty(IndentedStringBuilder builder, HierarchyInfo containingType, DependencyPropertyInfo property, InstancePropertyInfo instance, CacheBits? bits, BoxesInfo boxes)
	{
		var name = HierarchyInfo.EscapeIdentifier(property.Name);
		var identifierName = property.Name + "Property";
		var backingFieldName = $"__{identifierName}BackingField";

		builder.AppendLineIndented($"{instance.Modifiers} {property.PropertyType} {name}");
		using (builder.Block())
		{
			var getterPrefix = Prefix(instance.GetterModifiers);
			if (bits is { } cache)
			{
				builder.AppendLineIndented($"{getterPrefix}get");
				using (builder.Block())
				{
					builder.AppendLineIndented($"if (({cache.Cached.Field} & {cache.Cached.Mask}) == 0)");
					using (builder.Block())
					{
						if (cache.Value is { } valueBit)
						{
							WriteBooleanFlagUpdate(builder, "", $"(bool)GetValue({identifierName})", valueBit);
						}
						else
						{
							builder.AppendLineIndented($"{backingFieldName} = ({property.PropertyType})GetValue({identifierName});");
						}

						builder.AppendLineIndented($"{cache.Cached.Field} |= {cache.Cached.Mask};");
					}

					builder.AppendLine();
					builder.AppendLineIndented(cache.Value is { } value
						? $"return ({value.Field} & {value.Mask}) != 0;"
						: $"return {backingFieldName};");
				}
			}
			else
			{
				builder.AppendLineIndented($"{getterPrefix}get => ({property.PropertyType})GetValue({identifierName});");
			}

			if (instance.SetterModifiers is { } setterModifiers)
			{
				builder.AppendLineIndented($"{Prefix(setterModifiers)}set => SetValue({identifierName}, {GetBoxedValue("value", property.PropertyType, boxes)});");
			}
		}

		if (bits is { Value: null })
		{
			builder.AppendLine();
			builder.AppendLineIndented($"private {property.PropertyType} {backingFieldName};");
		}

		builder.AppendLine();
		WriteCreateMethod(builder, containingType, property, boxes, "Register", bits is null ? null : $"On{property.Name}BackingFieldUpdate");

		if (bits is { } updateBits)
		{
			builder.AppendLine();
			builder.AppendLineIndented($"private static void On{property.Name}BackingFieldUpdate({DependencyObjectType} instance, object newValue)");
			using (builder.Block())
			{
				builder.AppendLineIndented($"var typedInstance = ({containingType.FullyQualifiedName})instance;");
				if (updateBits.Value is { } valueBit)
				{
					WriteBooleanFlagUpdate(builder, "typedInstance.", "(bool)newValue", valueBit);
				}
				else
				{
					builder.AppendLineIndented($"typedInstance.{backingFieldName} = ({property.PropertyType})newValue;");
				}

				builder.AppendLineIndented($"typedInstance.{updateBits.Cached.Field} |= {updateBits.Cached.Mask};");
			}
		}
	}

	private static void WriteBooleanFlagUpdate(IndentedStringBuilder builder, string receiver, string condition, FlagBit bit)
	{
		builder.AppendLineIndented($"if ({condition})");
		using (builder.Block())
		{
			builder.AppendLineIndented($"{receiver}{bit.Field} |= {bit.Mask};");
		}

		builder.AppendLineIndented("else");
		using (builder.Block())
		{
			builder.AppendLineIndented($"{receiver}{bit.Field} &= ~{bit.Mask};");
		}

		builder.AppendLine();
	}

	private static void WriteAttachedProperty(
		IndentedStringBuilder builder,
		HierarchyInfo containingType,
		DependencyPropertyInfo property,
		AttachedPropertyInfo attached,
		BoxesInfo boxes,
		List<(HierarchyInfo Owner, List<string> Fields)> backingFieldOwners)
	{
		var identifierName = property.Name + "Property";
		var getValueName = $"Get{property.Name}Value";
		var setValueName = $"Set{property.Name}Value";
		var getter = attached.Getter;
		var getterThis = getter.IsExtension ? "this " : "";

		builder.AppendLineIndented($"{getter.Modifiers} {property.PropertyType} Get{property.Name}({getterThis}{attached.TargetType} {getter.TargetParameterName}) => {getValueName}({getter.TargetParameterName});");

		if (attached.Setter is { } setter)
		{
			var setterThis = setter.IsExtension ? "this " : "";
			builder.AppendLine();
			builder.AppendLineIndented($"{setter.Modifiers} void Set{property.Name}({setterThis}{attached.TargetType} {setter.TargetParameterName}, {property.PropertyType} {setter.ValueParameterName}) => {setValueName}({setter.TargetParameterName}, {setter.ValueParameterName});");
		}

		builder.AppendLine();

		if (attached.BackingFieldOwner is { } owner)
		{
			var ownerType = owner.ContainingType.FullyQualifiedName;
			AddBackingFields(backingFieldOwners, owner.ContainingType, property.PropertyType, owner.FieldName);

			builder.AppendLineIndented($"private static {property.PropertyType} {getValueName}({attached.TargetType} instance)");
			using (builder.Block())
			{
				builder.AppendLineIndented($"if (instance is {ownerType} backingFieldOwner)");
				using (builder.Block())
				{
					builder.AppendLineIndented($"if (!backingFieldOwner.{owner.FieldName}Set)");
					using (builder.Block())
					{
						builder.AppendLineIndented($"backingFieldOwner.{owner.FieldName} = ({property.PropertyType})instance.GetValue({identifierName});");
						builder.AppendLineIndented($"backingFieldOwner.{owner.FieldName}Set = true;");
					}

					builder.AppendLine();
					builder.AppendLineIndented($"return backingFieldOwner.{owner.FieldName};");
				}

				builder.AppendLine();
				builder.AppendLineIndented($"return ({property.PropertyType})instance.GetValue({identifierName});");
			}
		}
		else
		{
			builder.AppendLineIndented($"private static {property.PropertyType} {getValueName}({attached.TargetType} instance) => ({property.PropertyType})instance.GetValue({identifierName});");
		}

		builder.AppendLine();
		builder.AppendLineIndented($"private static void {setValueName}({attached.TargetType} instance, {property.PropertyType} value) => instance.SetValue({identifierName}, {GetBoxedValue("value", property.PropertyType, boxes)});");

		builder.AppendLine();
		WriteCreateMethod(builder, containingType, property, boxes, "RegisterAttached", attached.BackingFieldOwner is null ? null : $"On{property.Name}BackingFieldUpdate");

		if (attached.BackingFieldOwner is { } updateOwner)
		{
			builder.AppendLine();
			builder.AppendLineIndented($"private static void On{property.Name}BackingFieldUpdate({DependencyObjectType} instance, object newValue)");
			using (builder.Block())
			{
				builder.AppendLineIndented($"if (instance is {updateOwner.ContainingType.FullyQualifiedName} backingFieldOwner)");
				using (builder.Block())
				{
					builder.AppendLineIndented($"backingFieldOwner.{updateOwner.FieldName} = ({property.PropertyType})newValue;");
					builder.AppendLineIndented($"backingFieldOwner.{updateOwner.FieldName}Set = true;");
				}
			}
		}
	}

	private static void WriteCreateMethod(IndentedStringBuilder builder, HierarchyInfo containingType, DependencyPropertyInfo property, BoxesInfo boxes, string registerMethod, string? backingFieldUpdateCallback)
	{
		builder.AppendLineIndented($"private static {DependencyPropertyType} Create{property.Name}Property()");
		using (builder.Indent())
		{
			builder.AppendLineIndented($"=> {DependencyPropertyType}.{registerMethod}(");
			using (builder.Indent())
			{
				builder.AppendLineIndented($"\"{property.Name}\",");
				builder.AppendLineIndented($"typeof({property.PropertyType}),");
				builder.AppendLineIndented($"typeof({containingType.FullyQualifiedName}),");

				// Every argument is named so the call always binds to the one constructor that takes them all.
				builder.AppendLineIndented("new global::Microsoft.UI.Xaml.FrameworkPropertyMetadata(");
				using (builder.Indent())
				{
					builder.AppendLineIndented($"defaultValue: {GetDefaultValue(property.DefaultValue, boxes)},");
					builder.AppendLineIndented($"options: {property.Options},");
					builder.AppendLineIndented($"propertyChangedCallback: {(property.ChangedCallback is { } changed ? $"static (instance, args) => {changed}" : "null")},");
					builder.AppendLineIndented($"coerceValueCallback: {(property.CoerceCallback is { } coerce ? $"static (instance, baseValue, precedence) => {coerce}" : "null")},");
					builder.AppendLineIndented($"backingFieldUpdateCallback: {backingFieldUpdateCallback ?? "null"}));");
				}
			}
		}
	}

	private static void WriteHierarchy(IndentedStringBuilder builder, HierarchyInfo hierarchy, Action writeMembers)
	{
		builder.AppendLine();

		var disposables = new Stack<IDisposable>();
		if (hierarchy.Namespace.Length > 0)
		{
			builder.AppendLineIndented($"namespace {hierarchy.Namespace}");
			disposables.Push(builder.Block());
		}

		foreach (var type in hierarchy.Types)
		{
			builder.AppendLineIndented($"partial {type.Keyword} {type.Name}");
			disposables.Push(builder.Block());
		}

		writeMembers();

		while (disposables.Count > 0)
		{
			disposables.Pop().Dispose();
		}
	}

	private static void AddBackingFields(List<(HierarchyInfo Owner, List<string> Fields)> owners, HierarchyInfo owner, string propertyType, string fieldName)
	{
		var fields = owners.FirstOrDefault(o => o.Owner == owner).Fields;
		if (fields is null)
		{
			fields = new List<string>();
			owners.Add((owner, fields));
		}

		fields.Add($"internal {propertyType} {fieldName};");
		fields.Add($"internal bool {fieldName}Set;");
	}

	private static string GetBoxedValue(string expression, string type, BoxesInfo boxes)
		=> boxes.IsAccessible && boxes.BoxableTypes.AsImmutableArray().Contains(type)
			? $"{BoxesNamespace}.Boxer.Box({expression})"
			: expression;

	private static string GetDefaultValue(DefaultValueInfo defaultValue, BoxesInfo boxes)
	{
		if (boxes.IsAccessible && defaultValue.CachedBox is { } cachedBox && boxes.CachedBoxes.AsImmutableArray().Contains(cachedBox))
		{
			return $"{BoxesNamespace}.{cachedBox}";
		}

		return defaultValue.BoxableType is { } boxableType
			? GetBoxedValue(defaultValue.Expression, boxableType, boxes)
			: defaultValue.Expression;
	}

	private static string Prefix(string modifiers) => modifiers.Length > 0 ? modifiers + " " : "";

	/// <summary>
	/// Assigns the bits used by the local cache of instance properties: one "cached" bit each, plus one for the value of a
	/// <see cref="bool"/> property, packed 32 per <c>uint</c> field.
	/// </summary>
	private static CacheBits?[] AllocateCacheBits(EquatableArray<DependencyPropertyInfo> properties, out int flagsFieldCount)
	{
		var result = new CacheBits?[properties.Count];
		var nextBit = 0;

		for (var i = 0; i < properties.Count; i++)
		{
			var property = properties[i];
			if (property.Instance is null || !property.LocalCache)
			{
				continue;
			}

			var cached = CreateFlagBit(nextBit++);
			var value = property.IsBoolean ? CreateFlagBit(nextBit++) : (FlagBit?)null;
			result[i] = new CacheBits(cached, value);
		}

		flagsFieldCount = (nextBit + 31) / 32;
		return result;
	}

	private static FlagBit CreateFlagBit(int bit) => new($"{FlagsFieldPrefix}{bit / 32}", $"(1u << {bit % 32})");

	private readonly record struct FlagBit(string Field, string Mask);

	private readonly record struct CacheBits(FlagBit Cached, FlagBit? Value);
}
